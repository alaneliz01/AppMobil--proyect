-- CREACION DE TABLA DE ALUMNO
CREATE TABLE ALUMNO
(
    IdAlumno INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(50) NOT NULL,
    APaterno VARCHAR(80) NOT NULL,
    AMaterno VARCHAR(80) NOT NULL,
    IdCarrera TINYINT NOT NULL,
    FecRegistro SMALLDATETIME NOT NULL
        CONSTRAINT DF_FecRegistro_ALU DEFAULT (GETDATE()),
    CONSTRAINT PK_IdAlumno_ALU PRIMARY KEY (IdAlumno),
    CONSTRAINT FK_IdCarrera_ALU FOREIGN KEY (IdCarrera) REFERENCES CARRERA (IdCarrera)
)


CREATE TABLE MAESTRO
(
    IdMaestro INT IDENTITY(1,1) NOT NULL,
    Nombre VARCHAR(50) NOT NULL,
    APaterno VARCHAR(80) NOT NULL,
    AMaterno VARCHAR(80) NOT NULL,
    FecRegistro SMALLDATETIME NOT NULL
        CONSTRAINT DF_FecRegistro_MAE DEFAULT (GETDATE()),
    CONSTRAINT PK_IdMaestro_MAE PRIMARY KEY (IdMaestro)
)